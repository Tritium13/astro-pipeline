"""Stage 9.3: explorer mode – pick a random suitable public JWST imaging dataset,
write a default TOML config for it and (optionally) run the pipeline.

Usage (in the project folder):
    python -m astropipe.explore                  # random month, run pipeline
    python -m astropipe.explore --seed 42        # reproducible choice
    python -m astropipe.explore --no-run         # only find a candidate + write config
    python -m astropipe.explore --program 12591 --no-run   # list a given programme, pick the richest observation
    python -m astropipe.explore --program 12591 --obs jw12591-o002_t001   # a specific observation

Suitability rules (see PLAN.md, stage 9):
  * NIRCam imaging, calibration level 3, public, science intent
  * not a Solar-System (moving) target, finite coordinates
  * one observation (same pointing) with >= 3 different filters
  * exactly one i2d file per filter, total size <= max_gb
"""
import argparse
import random
import re
from pathlib import Path

import numpy as np
from astropy.time import Time
from astroquery.mast import Observations

from . import bands as bands_mod, mast

JWST_SCIENCE_START = Time("2022-07-12").mjd
SOLAR_SYSTEM = re.compile(r"solar system|planet|comet|asteroid|moon|satellite|kuiper|trans-neptunian", re.I)


def band_from_filters(filters):
    """'F444W;F405N' -> 'F405N' (narrow/medium filter in the pupil defines the band)."""
    parts = [p.strip().upper() for p in str(filters).split(";") if p.strip()]
    narrow = [p for p in parts if p[-1] in "NM"]
    return (narrow or parts)[0]


def query_window(start_mjd, days=30, instrument="NIRCAM/IMAGE"):
    obs = Observations.query_criteria(
        obs_collection="JWST", instrument_name=instrument, calib_level=3,
        dataRights="PUBLIC", intentType="science", t_min=[start_mjd, start_mjd + days],
    )
    return obs


def group_candidates(obs, min_bands=3):
    """Group level-3 observations by observation prefix (e.g. jw02733-o001_t001)."""
    groups = {}
    for row in obs:
        cls = str(row["target_classification"]) if "target_classification" in obs.colnames else ""
        if SOLAR_SYSTEM.search(cls) or not (np.isfinite(row["s_ra"]) and np.isfinite(row["s_dec"])):
            continue
        prefix = str(row["obs_id"]).split("_nircam")[0]
        g = groups.setdefault(prefix, {"prefix": prefix, "target": str(row["target_name"]),
                                       "program": int(row["proposal_id"]), "bands": set(),
                                       "title": str(row["obs_title"]) if "obs_title" in obs.colnames else "",
                                       "ra": float(row["s_ra"]), "dec": float(row["s_dec"]), "classification": cls})
        g["bands"].add(band_from_filters(row["filters"]))
    return [g for g in groups.values() if len(g["bands"]) >= min_bands]


def check_products(cand, max_gb=3.0, instrument="NIRCAM/IMAGE"):
    """Return (ok, reason, i2d table) – one i2d per band, total size <= max_gb."""
    obs, prods = mast.find_i2d(cand["program"], instrument)
    sel = prods[[cand["prefix"] + "_" in str(n) for n in prods["productFilename"]]]
    per_band = {}
    for name in sel["productFilename"]:
        tokens = [t.upper() for t in re.findall(r"f\d{3,4}[wmn]2?", str(name).lower())]
        narrow = [t for t in tokens if t[-1] in "NM"]
        b = (narrow or tokens)[0] if tokens else None
        per_band.setdefault(b, []).append(name)
    if any(len(v) > 1 for v in per_band.values()):
        return False, "several i2d files per filter", sel
    size = mast.total_size_gb(sel)
    if size > max_gb:
        return False, f"too large ({size:.2f} GB)", sel
    if len(per_band) < 3:
        return False, "fewer than 3 filters with i2d", sel
    return True, f"{len(per_band)} filters, {size:.2f} GB", sel


def slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:40]


def write_config(cand, path, max_gb=3.0):
    b = bands_mod.sort_bands(cand["bands"])
    name = f"explore_{cand['prefix'].replace('-', '_')}_{slug(cand['target'])}"
    bands_toml = ", ".join(f'"{x}"' for x in b)
    title = cand["target"].replace('"', "'")
    desc = (f"JWST NIRCam imaging, programme {cand['program']}"
            + (f" ('{cand['title']}')" if cand["title"] and cand["title"] != "--" else "") + ".").replace('"', "'")
    text = f'''# Generated by astropipe.explore – default values, refine by hand.
# Target: {cand['target']}  |  RA {cand['ra']:.5f}  Dec {cand['dec']:.5f}  |  classification: {cand['classification']}

[run]
name = "{name}"

[data]
program = {cand['program']}
instrument = "NIRCAM/IMAGE"
raw_dir = "{name}_nircam"
obs = "{cand['prefix']}_"
bands = [{bands_toml}]
max_gb = {max_gb}

[clean]
method = "auto"          # measures sky fraction + stripe strength per filter and picks the cleaning (see params/*_run.json)

[grid]
resolution_arcsec = 0.063

[background]
box = 150
edge_margin = 150
n_boxes = 6
min_sep = 500
drop_negative = true

[stretch]
black_k = 0.5
white_pct = 99.9
a = 0.05

[color.A_chromatic]
mode = "chromatic"
label = "hues by wavelength, 240° to 0°"

[export]
variants = ["A_chromatic"]
center = "auto"          # brightness centre, falls back to the most interior point
center_band = "{b[-1]}"
margin = 100
aspect = 1.0

[caption]
title = "{title} – JWST NIRCam"
description = "{desc}"
filter_source = ""
credits = "Data: NASA, ESA, CSA, STScI (programme {cand['program']}), retrieved via MAST. Processing: Tritium13 (automatic explorer run, default parameters)."
'''
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path, name


def find_candidate(seed=None, max_gb=3.0, days=30, max_windows=5, max_checks=8, verbose=True):
    """Draw random time windows until a suitable candidate is found. Returns (cand, info)."""
    rng = random.Random(seed)
    # Window range ends ~400 d ago (beyond the usual 12-month exclusive access period),
    # rounded down to the 1st of the month -> same seed = same windows within a month.
    now = Time.now().datetime
    end = Time(f"{now.year:04d}-{now.month:02d}-01").mjd - 400
    tried = []
    for _ in range(max_windows):
        start = rng.uniform(JWST_SCIENCE_START, end - days)
        obs = query_window(start, days)
        cands = group_candidates(obs)
        if verbose:
            print(f"window {Time(start, format='mjd').iso[:10]} + {days} d: {len(obs)} observations, {len(cands)} candidates")
        cands.sort(key=lambda c: c["prefix"])   # MAST row order is not guaranteed -> sort before shuffling
        rng.shuffle(cands)
        for cand in cands[:max_checks]:
            ok, reason, sel = check_products(cand, max_gb)
            tried.append((cand["prefix"], cand["target"], reason))
            if verbose:
                print(f"  {cand['prefix']:<22} {cand['target'][:28]:<28} {sorted(cand['bands'])} -> {reason}")
            if ok:
                return cand, {"window_start": Time(start, format="mjd").iso[:10], "tried": tried}
    raise RuntimeError("no suitable candidate found – try again or raise max_gb/max_windows")


def write_report(cand, result, path, offset_warn_px=0.5, bad_frac_warn=1e-3):
    """Short Markdown report with automatic warnings for an explorer run."""
    e, st = result["export"], result["stretch"]
    warn = []
    if e.get("center_mode") == "interior":
        warn.append("Crop around the most interior point of the field (no central object detected) – check the choice of subject by hand.")
    big = {b: v for b, v in result["star_offsets_px"].items() if v is not None and v > offset_warn_px}
    if big:
        warn.append("Large star offset within one observation: "
                    + ", ".join(f"{b} {v:.2f} px" for b, v in big.items())
                    + " – possibly saturated stars/galaxies used as fiducials; look for colour fringes at stars.")
    holes = st.get("saturated_holes_filled_px", {})
    npx = result.get("grid_shape") and result["grid_shape"][0] * result["grid_shape"][1]
    bad = {b: v["bad_px"] for b, v in holes.items() if isinstance(v, dict) and v.get("bad_px", 0) > 0}
    if npx:
        bad = {b: v / npx for b, v in bad.items() if v / npx > bad_frac_warn}
        if bad:
            warn.append("Many bad/flagged pixels filled: "
                        + ", ".join(f"{b} {100 * v:.2f} %" for b, v in bad.items()))
    if e.get("brightness_center_yx") and e.get("center_mode") == "interior":
        warn.append("Intensity-weighted centre (red cross in the overview) lies at a gap or at the edge – "
                    "the main object probably lies in a detector gap.")
    if len(st["sky_boxes"]["yx"]) < 3:
        warn.append(f"Only {len(st['sky_boxes']['yx'])} sky boxes – background uncertain.")
    au = (result.get("clean") or {}).get("auto")
    if au:
        strong = {b: max(m["stripes_rows"], m["stripes_columns"]) for b, m in au["measured"].items()
                  if au["chosen"][b]["method"] != "none"}
        kind = "empty field (sky dominates)" if au["empty_field"] else "object fills the field"
        if strong:
            warn.append(f"Stripes detected ({kind}): " + ", ".join(f"{b} {v:.2f}" for b, v in strong.items())
                        + " (stripe strength / sky noise; pure noise ≈ 0.06). Corrected with "
                        + ", ".join(sorted({au['chosen'][b]['method'] for b in strong}))
                        + (" + 2-D background" if au["empty_field"] else "")
                        + ". Residuals cannot be fully removed in the i2d when single exposures are offset (known limitation).")
    warn.append("Always check by hand (not detected automatically): stray light/diffuse veils in single filters, "
                "stripes (then `clean.method = \"local\"`), darker bands between detectors.")
    lines = [f"# Explorer report: {cand['target']} ({cand['prefix']})", "",
             f"- Programme: {cand['program']} – {cand['title']}",
             f"- Position: RA {cand['ra']:.5f}, Dec {cand['dec']:.5f}; classification: {cand['classification']}",
             f"- Filters: {', '.join(sorted(cand['bands']))}",
             f"- Crop: {e['size_arcmin'][0]:.2f}′ × {e['size_arcmin'][1]:.2f}′ (centre: {e.get('center_mode')})",
             f"- Sky boxes: {len(st['sky_boxes']['yx'])}",
             f"- Runtime: {result['runtime_s']} s",
             f"- Configuration: `{result['config']}`"]
    ov = [f for f in e.get("files", {}).get(next(iter(e.get("files", {})), ""), []) if f.endswith("_overview.jpg")]
    if ov:
        lines.append(f"- Overview (whole field, frame = crop): `{ov[0]}`")
    lines += ["", "## Notes", ""]
    lines += [f"- {w}" for w in warn]
    text = "\n".join(lines) + "\n"
    Path(path).write_text(text, encoding="utf-8")
    return text


def find_in_program(program, prefix=None, max_gb=3.0, instrument="NIRCAM/IMAGE", verbose=True):
    """Pick an observation from a given programme instead of a random window.

    Lists all observations with >= 3 filters; uses `prefix` (e.g. 'jw12591-o002_t001') if given,
    otherwise the first suitable one with the most filters. Returns (cand, info)."""
    obs, _ = mast.find_i2d(program, instrument)
    if len(obs) == 0:
        raise RuntimeError(f"programme {program}: no public level-3 {instrument} data found")
    cands = sorted(group_candidates(obs), key=lambda c: (-len(c["bands"]), c["prefix"]))
    if prefix:
        cands = [c for c in cands if c["prefix"] == prefix.rstrip("_")]
        if not cands:
            raise RuntimeError(f"{prefix}: not found or fewer than 3 filters in programme {program}")
    tried = []
    for cand in cands:
        ok, reason, sel = check_products(cand, max_gb, instrument)
        tried.append((cand["prefix"], cand["target"], reason))
        if verbose:
            print(f"  {cand['prefix']:<22} {cand['target'][:28]:<28} {sorted(cand['bands'])} -> {reason}")
        if ok:
            return cand, {"program": program, "tried": tried}
    raise RuntimeError(f"programme {program}: no observation passed the checks (see list above)")


def main():
    ap = argparse.ArgumentParser(description="Explorer mode: random suitable JWST NIRCam dataset.")
    ap.add_argument("--seed", type=int, default=None)
    ap.add_argument("--max-gb", type=float, default=3.0)
    ap.add_argument("--no-run", action="store_true")
    ap.add_argument("--program", type=int, default=None, help="use this programme instead of a random window")
    ap.add_argument("--obs", default=None, help="observation prefix within --program, e.g. jw12591-o002_t001")
    args = ap.parse_args()
    if args.program:
        cand, info = find_in_program(args.program, args.obs, args.max_gb)
    else:
        cand, info = find_candidate(args.seed, args.max_gb)
    cfg_path, name = write_config(cand, Path("configs") / "explore" / f"{cand['prefix']}.toml", args.max_gb)
    print(f"\nchosen: {cand['target']} ({cand['prefix']}), bands {sorted(cand['bands'])}\nconfig: {cfg_path}")
    if not args.no_run:
        from .run import run
        result = run(cfg_path, Path("."))
        print(write_report(cand, result, Path("output") / "runs" / f"{cand['prefix']}_report.md"))


if __name__ == "__main__":
    main()
